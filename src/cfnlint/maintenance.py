import json
import logging
import os
import subprocess
import tempfile
from urllib.parse import urlparse

import cfnlint
import cfnlint.data.AdditionalSpecs
from cfnlint.helpers import get_url_content
from cfnlint.schema import PROVIDER_SCHEMA_MANAGER

LOGGER = logging.getLogger(__name__)

# Hosts permitted as sources for the service-reference index and the
# per-service documents it links to. Anything else -- including other
# schemes such as ``file:``, ``ftp:`` or ``data:`` that ``urlopen``
# would otherwise accept -- is rejected before the fetch.
_SERVICE_REFERENCE_ALLOWED_HOSTS = frozenset(
    {
        "servicereference.us-east-1.amazonaws.com",
    }
)


def _validate_service_reference_url(url):
    """Return ``url`` if it is an https URL on the service-reference allowlist.

    Raises ``ValueError`` otherwise. The index response is treated as
    untrusted input: a tampered or MITM'd response must not be able to
    coerce ``urlopen`` into reading ``file://`` paths or contacting an
    arbitrary host.
    """
    if not isinstance(url, str):
        raise ValueError(f"Service URL must be a string, got {type(url).__name__}")
    parsed = urlparse(url)
    if parsed.scheme != "https":
        raise ValueError(
            f"Refusing to fetch service URL with scheme {parsed.scheme!r}: {url}"
        )
    host = (parsed.hostname or "").lower()
    if host not in _SERVICE_REFERENCE_ALLOWED_HOSTS:
        raise ValueError(
            f"Refusing to fetch service URL from unexpected host {host!r}: {url}"
        )
    return url


def update_resource_specs(force: bool = False) -> int:
    """Update provider schemas from the enhanced schemas repository.

    Args:
        force: force the schemas to be downloaded

    Returns:
        int: exit code (0=success, 2=failure)
    """
    return PROVIDER_SCHEMA_MANAGER.update(force)


def update_documentation(rules):
    # Update the overview of all rules in the linter
    filename = "docs/rules.md"

    # Sort rules by the Rule ID
    sorted_rules = sorted(rules.values(), key=lambda obj: obj.id)
    data = []

    # Read current file up to the Rules part, everything up to that point is
    # static documentation.
    with open(filename, "r", encoding="utf-8") as original_file:
        line = original_file.readline()
        while line:
            data.append(line)

            if line == "## Rules\n":
                break

            line = original_file.readline()

    # Rebuild the file content
    with open(filename, "w", encoding="utf-8") as new_file:
        # Rewrite the static documentation
        for line in data:
            new_file.write(line)

        # Add the rules
        new_file.write(
            "(_This documentation is generated by running `cfn-lint"
            " --update-documentation`, do not alter this manually_)\n\n"
        )
        new_file.write(
            f"The following **{len(sorted_rules) + 3}** rules are applied by this"
            " linter:\n\n"
        )
        new_file.write(
            "| Rule ID  | Title | Description | Config<br />(Name:Type:Default) |"
            " Source | Tags |\n"
        )
        new_file.write(
            "| -------- | ----- | ----------- | ---------- | ------ | ---- |\n"
        )

        rule_output = (
            '| [{0}<a name="{0}"></a>]({6}) | {1} | {2} | {3} | [Source]({4}) | {5} |\n'
        )

        for rule in sorted_rules:
            rule_source_code_file = (
                "../"
                + subprocess.check_output(
                    [
                        "git",
                        "grep",
                        "-l",
                        'id = "' + rule.id + '"',
                        "src/cfnlint/rules/",
                    ]
                )
                .decode("ascii")
                .strip()
            )
            rule_id = rule.id + "*" if rule.experimental else rule.id
            tags = ",".join(f"`{tag}`" for tag in rule.tags)
            config = "<br />".join(
                f"{key}:{values.get('type')}:{values.get('default')}"
                for key, values in rule.config_definition.items()
            )
            new_file.write(
                rule_output.format(
                    rule_id,
                    rule.shortdesc,
                    rule.description,
                    config,
                    rule.source_url,
                    tags,
                    rule_source_code_file,
                )
            )
        new_file.write("\n\\* experimental rules\n")


def update_iam_policies():
    """update iam policies file"""

    url = "https://servicereference.us-east-1.amazonaws.com"

    filename = os.path.join(
        os.path.dirname(cfnlint.data.AdditionalSpecs.__file__), "Policies.json"
    )
    LOGGER.debug("Downloading policies %s into %s", url, filename)

    services = json.loads(get_url_content(_validate_service_reference_url(url)))
    if not isinstance(services, list):
        raise ValueError(
            "Service reference index must be a JSON array, "
            f"got {type(services).__name__}"
        )

    def _clean_arn_formats(arn):
        arn_parts = arn.split(":", 5)

        resource = arn_parts[5]
        delimiter = None
        for d in [":", "/"]:
            if d in resource:
                delimiter = d
                break
        else:
            delimiter = ":"

        if delimiter:
            resource_parts = []
            for resource_part in resource.split(delimiter):
                if "${" in resource_part:
                    resource_parts.append(".*")
                    break

                resource_parts.append(resource_part)

            arn_parts[5] = delimiter.join(resource_parts)

        return ":".join(arn_parts)

    def _processes_a_service(data):
        results = {
            "Actions": {},
            "Resources": {},
        }

        for action in data.get("Actions", []):
            results["Actions"][action.get("Name").lower()] = {}
            if "Resources" in action:
                results["Actions"][action.get("Name").lower()] = {
                    "Resources": list([i["Name"] for i in action["Resources"]])
                }

        for resource in data.get("Resources", []):
            results["Resources"][resource.get("Name").lower()] = {
                "ARNFormats": [
                    _clean_arn_formats(arn) for arn in resource.get("ARNFormats")
                ],
            }
            if "ConditionKeys" in resource:
                results["Resources"][resource.get("Name").lower()]["ConditionKeys"] = (
                    resource.get("ConditionKeys")
                )

        return results

    def _validate_service_payload(payload, service_name):
        if not isinstance(payload, dict):
            raise ValueError(
                f"Service {service_name!r} payload must be a JSON object, "
                f"got {type(payload).__name__}"
            )
        for key in ("Actions", "Resources"):
            value = payload.get(key, [])
            if not isinstance(value, list):
                raise ValueError(
                    f"Service {service_name!r} field {key!r} must be a list"
                )
            for entry in value:
                if not isinstance(entry, dict) or not isinstance(
                    entry.get("Name"), str
                ):
                    raise ValueError(
                        f"Service {service_name!r} {key!r} entries must be "
                        "objects with a string 'Name'"
                    )
        for resource in payload.get("Resources", []):
            arn_formats = resource.get("ARNFormats")
            if not isinstance(arn_formats, list) or not all(
                isinstance(a, str) for a in arn_formats
            ):
                raise ValueError(
                    f"Service {service_name!r} resource "
                    f"{resource.get('Name')!r} must have a list of string "
                    "'ARNFormats'"
                )
        return payload

    data = {}
    for service in services:
        if not isinstance(service, dict):
            raise ValueError(
                "Service reference index entries must be objects, "
                f"got {type(service).__name__}"
            )
        name = service.get("service")
        if not isinstance(name, str) or not name:
            raise ValueError(
                "Service reference index entry is missing a string 'service'"
            )
        service_url = _validate_service_reference_url(service.get("url"))
        content = json.loads(get_url_content(service_url))
        data[name] = _processes_a_service(_validate_service_payload(content, name))

    # Write to a temporary file in the same directory and atomically
    # replace the destination so a failed/partial run can never leave a
    # truncated Policies.json behind.
    target_dir = os.path.dirname(filename) or "."
    fd, tmp_path = tempfile.mkstemp(
        prefix=".Policies.json.", suffix=".tmp", dir=target_dir
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=1, sort_keys=True, separators=(",", ": "))
            f.write("\n")
        os.replace(tmp_path, filename)
    except BaseException:
        try:
            os.remove(tmp_path)
        except OSError:
            pass
        raise
